#!/usr/bin/env node
// Guard: every change to the admin tour must be paired with a deliberate
// bump of CURRENT_TOUR_VERSION (so existing users get the tour again) and
// a matching lock-file refresh.
//
// How it works:
//   - Read src/tour/tour-config.ts as text
//   - Extract CURRENT_TOUR_VERSION literal
//   - Compute sha256 of the file with the version line stripped
//     (so the version itself does not feed back into the hash)
//   - Compare {version, sourceHash} against
//     src/tour/tour-version.lock.json
//
// Pass `--update` to regenerate the lock file after a deliberate change.
//
// Exit codes:
//   0 - in sync (or lock regenerated with --update)
//   1 - drift detected, or invalid inputs

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const TOUR_FILE = resolve(__dirname, "../src/tour/tour-config.ts");
const LOCK_FILE = resolve(__dirname, "../src/tour/tour-version.lock.json");

const VERSION_LINE_RE =
  /^\s*export\s+const\s+CURRENT_TOUR_VERSION\s*=\s*"([^"]+)"\s*;\s*$/m;

function fail(msg) {
  console.error("\n\x1b[31m✗ tour-version drift\x1b[0m");
  console.error(msg.trimEnd() + "\n");
  process.exit(1);
}

function loadTour() {
  let src;
  try {
    src = readFileSync(TOUR_FILE, "utf8");
  } catch (e) {
    fail(`Could not read ${TOUR_FILE}: ${e.message}`);
  }
  const m = src.match(VERSION_LINE_RE);
  if (!m) {
    fail(
      `Could not find a top-level\n  export const CURRENT_TOUR_VERSION = "...";\nin ${TOUR_FILE}.`,
    );
  }
  const version = m[1];
  // Hash the file contents with the version literal blanked out, so the
  // version string itself does not contribute to the hash. Anything else
  // that changes (steps, copy, comments) will move the hash.
  const normalized = src.replace(VERSION_LINE_RE, "// CURRENT_TOUR_VERSION");
  const sourceHash = createHash("sha256").update(normalized).digest("hex");
  return { version, sourceHash };
}

function loadLock() {
  try {
    const raw = readFileSync(LOCK_FILE, "utf8");
    const parsed = JSON.parse(raw);
    if (
      typeof parsed.version !== "string" ||
      typeof parsed.sourceHash !== "string"
    ) {
      fail(
        `${LOCK_FILE} is malformed. Expected JSON { "version": string, "sourceHash": string }.`,
      );
    }
    return parsed;
  } catch (e) {
    if (e.code === "ENOENT") return null;
    fail(`Could not read ${LOCK_FILE}: ${e.message}`);
  }
}

function writeLock({ version, sourceHash }) {
  const body = JSON.stringify(
    {
      $comment:
        "Generated by scripts/check-tour-version.mjs. Do not edit by hand. Run `pnpm --filter @workspace/claimclear run check-tour-version -- --update` after intentionally changing tour-config.ts.",
      version,
      sourceHash,
    },
    null,
    2,
  );
  writeFileSync(LOCK_FILE, body + "\n");
}

const args = process.argv.slice(2);
const updateMode = args.includes("--update");

const current = loadTour();

if (updateMode) {
  writeLock(current);
  console.log(
    `\x1b[32m✓\x1b[0m tour-version.lock.json regenerated (version=${current.version}).`,
  );
  process.exit(0);
}

const lock = loadLock();

if (!lock) {
  fail(
    `No lock file at ${LOCK_FILE}.\n\n` +
      `Generate it once with:\n` +
      `  pnpm --filter @workspace/claimclear run check-tour-version -- --update`,
  );
}

const versionDrift = lock.version !== current.version;
const hashDrift = lock.sourceHash !== current.sourceHash;

if (!versionDrift && !hashDrift) {
  console.log(
    `\x1b[32m✓\x1b[0m tour version in sync (version=${current.version}).`,
  );
  process.exit(0);
}

if (hashDrift && !versionDrift) {
  fail(
    `tour-config.ts changed but CURRENT_TOUR_VERSION was NOT bumped.\n\n` +
      `  current version: ${current.version}\n` +
      `  locked version : ${lock.version}\n\n` +
      `Why this matters: existing users only see the tour again when the\n` +
      `version string changes. Shipping new tour copy without bumping\n` +
      `CURRENT_TOUR_VERSION means everyone who already saw the old tour\n` +
      `will silently miss the new one.\n\n` +
      `Fix:\n` +
      `  1. Edit src/tour/tour-config.ts and bump CURRENT_TOUR_VERSION\n` +
      `     (e.g. "${nextVersionHint(current.version)}").\n` +
      `  2. Run: pnpm --filter @workspace/claimclear run check-tour-version -- --update\n` +
      `  3. Commit the updated tour-config.ts AND tour-version.lock.json together.`,
  );
}

if (versionDrift && !hashDrift) {
  fail(
    `CURRENT_TOUR_VERSION was bumped but the tour content did not change.\n\n` +
      `  current version: ${current.version}\n` +
      `  locked version : ${lock.version}\n\n` +
      `If this was a deliberate "force-replay" bump, regenerate the lock:\n` +
      `  pnpm --filter @workspace/claimclear run check-tour-version -- --update`,
  );
}

// Both differ — devs likely made a real change. They still need to refresh
// the lock so CI can verify the pairing. We do NOT auto-update here.
fail(
  `tour-config.ts changed AND CURRENT_TOUR_VERSION changed, but the lock\n` +
    `file is stale. This is the normal case after editing the tour — you\n` +
    `just need to refresh the lock so CI sees the pairing.\n\n` +
    `  current version: ${current.version}\n` +
    `  locked version : ${lock.version}\n\n` +
    `Fix:\n` +
    `  pnpm --filter @workspace/claimclear run check-tour-version -- --update\n\n` +
    `Then commit src/tour/tour-config.ts AND src/tour/tour-version.lock.json together.`,
);

function nextVersionHint(v) {
  // best-effort: bump trailing .vN if present, else append .v2
  const m = v.match(/^(.*\.v)(\d+)$/);
  if (m) return `${m[1]}${Number(m[2]) + 1}`;
  const today = new Date().toISOString().slice(0, 10);
  return `${today}.v1`;
}
