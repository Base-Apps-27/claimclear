interface SeedHandle {
  groupId: number;
  primaryClaimId: number;
  duplicateClaimId: number;
  errorTypeId: number;
}

async function seedGroupWithPerLegContextAndSibling(): Promise<SeedHandle> {
  const suffix = `${Date.now()}-${Math.floor(Math.random() * 1e6)}`;

  const [errType] = await db.insert(errorTypesTable).values({
    name: `T312-ErrType-${suffix}`,
    description: "Trip distance mismatch",
    guidance: "Verify GPS breadcrumbs.",
    decisionTree: null,
  }).returning();

  const [group] = await db.insert(invoiceGroupsTable).values({
    invoiceNumber: `T312-INV-${suffix}`,
    status: "Needs Evidence",
    outcome: "Pending",
    errorTypeId: String(errType.id),
    errorTypeName: errType.name,
    errorDetails: "Distance billed exceeds the contract distance for this leg.",
  }).returning();

  // Primary leg: has per_leg_context (drives perLegContextLegCount=1).
  const [primary] = await db.insert(claimsTable).values({
    confNumber: `T312-PRI-${suffix}`,
    invoiceGroupId: group.id,
    errorTypeId: String(errType.id),
    errorTypeName: errType.name,
    status: "Needs Evidence",
    outcome: "Pending",
    sopOutcome: "portal_dispute",
    includedInDispute: true,
    claimAmount: "42.50",
    date: "2026-01-15",
    clientNumber: "C100",
    carNumber: "CAR-7",
    perLegContext: "Driver waited 47 minutes; member confirmed delay.",
  }).returning();

  // Sibling duplicate rolled under the primary
  // (drives siblingDuplicateCount=1 on the primary's slice).
  const [duplicate] = await db.insert(claimsTable).values({
    confNumber: `T312-DUP-${suffix}`,
    invoiceGroupId: group.id,
    errorTypeId: String(errType.id),
    errorTypeName: errType.name,
    status: "Needs Evidence",
    outcome: "Pending",
    sopOutcome: "portal_dispute",
    includedInDispute: true,
    claimAmount: "55.00",
    date: "2026-01-16",
    clientNumber: "C100",
    carNumber: "CAR-7",
    duplicateOfClaimId: primary.id,
  }).returning();

  return {
    groupId: group.id,
    primaryClaimId: primary.id,
    duplicateClaimId: duplicate.id,
    errorTypeId: errType.id,
  };
}

async function cleanupSeed(seed: SeedHandle): Promise<void> {
  await db.delete(stateEventsTable).where(eq(stateEventsTable.invoiceGroupId, seed.groupId)).catch(() => undefined);
  await db.delete(portalSubmissionsTable).where(eq(portalSubmissionsTable.invoiceGroupId, seed.groupId)).catch(() => undefined);
  await db.delete(auditLogsTable).where(eq(auditLogsTable.invoiceGroupId, seed.groupId)).catch(() => undefined);
  for (const id of [seed.primaryClaimId, seed.duplicateClaimId]) {
    await db.delete(stateEventsTable).where(eq(stateEventsTable.claimId, id)).catch(() => undefined);
    await db.delete(auditLogsTable).where(eq(auditLogsTable.claimId, id)).catch(() => undefined);
    await db.delete(notesTable).where(eq(notesTable.claimId, id)).catch(() => undefined);
    await db.delete(claimEvidenceTable).where(eq(claimEvidenceTable.claimId, id)).catch(() => undefined);
    await db.delete(claimsTable).where(eq(claimsTable.id, id)).catch(() => undefined);
  }
  await db.delete(claimEvidenceTable).where(eq(claimEvidenceTable.invoiceGroupId, seed.groupId)).catch(() => undefined);
  await db.delete(invoiceGroupsTable).where(eq(invoiceGroupsTable.id, seed.groupId)).catch(() => undefined);
  await db.delete(errorTypesTable).where(eq(errorTypesTable.id, seed.errorTypeId)).catch(() => undefined);
}

/**
 * Pull the latest audit row for `(groupId, action)` and return its
 * metadata. Asserts a single matching row exists so we don't silently
 * miss duplicates from earlier-stored runs (cleanup happens in `finally`,
 * but a fresh group per test makes this a tight invariant).
 */
async function latestAuditMetadata(opts: {
  groupId?: number;
  claimId?: number;
  action: string;
}): Promise<Record<string, unknown>> {
  const conditions = [eq(auditLogsTable.action, opts.action)];
  if (opts.groupId !== undefined) conditions.push(eq(auditLogsTable.invoiceGroupId, opts.groupId));
  if (opts.claimId !== undefined) conditions.push(eq(auditLogsTable.claimId, opts.claimId));
  const rows = await db.select().from(auditLogsTable).where(and(...conditions));
  assert.equal(rows.length, 1, `expected exactly one '${opts.action}' audit row, found ${rows.length}`);
  const meta = rows[0].metadata;
  assert.ok(meta && typeof meta === "object", `'${opts.action}' audit row has no metadata`);
  return meta as Record<string, unknown>;
}

/**
 * Shared assertion: every audited prompt site must surface the three
 * traceability counters. Asserting on exact key presence catches a key
 * being renamed or omitted; asserting on values catches a routing bug
 * where the wrong `promptLegInputs` was threaded into the metadata.
 */
function assertCountersPresent(meta: Record<string, unknown>, expected: {
  hasPerLegContext: boolean;
  perLegContextLegCount: number;
  siblingDuplicateCount: number;
}): void {
  assert.ok(Object.prototype.hasOwnProperty.call(meta, "hasPerLegContext"), "metadata missing hasPerLegContext");
  assert.ok(Object.prototype.hasOwnProperty.call(meta, "perLegContextLegCount"), "metadata missing perLegContextLegCount");
  assert.ok(Object.prototype.hasOwnProperty.call(meta, "siblingDuplicateCount"), "metadata missing siblingDuplicateCount");
  assert.equal(meta.hasPerLegContext, expected.hasPerLegContext);
  assert.equal(meta.perLegContextLegCount, expected.perLegContextLegCount);
  assert.equal(meta.siblingDuplicateCount, expected.siblingDuplicateCount);
}

