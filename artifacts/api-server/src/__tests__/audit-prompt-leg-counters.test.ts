/**
 * Task #312 integration tests: every audit-log event that fires alongside a
 * `buildPromptLegInputs`-derived Claude prompt must carry the three
 * traceability counters (`hasPerLegContext`, `perLegContextLegCount`,
 * `siblingDuplicateCount`) so we can answer "did the AI see the per-leg
 * finding when it drafted this?" from the audit log alone.
 *
 * Four prompt sites → four audited events:
 *   - portal_understanding_preflight  (POST /portal-submissions/preflight-understanding)
 *   - portal_draft_created            (POST /portal-submissions/generate-preview)
 *   - portal_draft_regenerated        (POST /portal-submissions/:id/regenerate)
 *   - email_generated                 (POST /claims/:id/generate-email)
 *
 * The Anthropic SDK is stubbed via `__setAnthropicClientForTesting` so we
 * can exercise real route handlers end-to-end without provisioning
 * credentials. Each test seeds a fresh invoice group with a primary leg
 * (per_leg_context set) and a sibling duplicate, so the helper produces
 * non-zero counters and the assertions can pin all three values.
 */

